## 7. Addition — counting on

**Rule.** $a + b$: start at $a$, count on $b$.

$$1 + 1 = 2$$

**Examples.**

| sum | count on | answer |
|---|---|---|
| $1+1$ | 2 | $2$ |
| $6+3$ | 7, 8, 9 | $9$ |
| $4+5$ | 5, 6, 7, 8, 9 | $9$ |
| $8+2$ | 9, 10 | $10$ |
| $7+0$ | — | $7$ |

**Three facts that cut the work.**

$$a + b = b + a \qquad a + 0 = a \qquad \text{the pairs making ten}$$

Flip to save work: $2+9$ is $9$ count on $2$. And $a+b=b+a$ cuts the $100$ digit sums to $55$.

**Pairs that make ten.** $1+9$, $2+8$, $3+7$, $4+6$, $5+5$.

```drill
make-ten
```

**A bigger number plus a small one.** Only the ones move.

| sum | ones | answer |
|---|---|---|
| $10+1$ | $0+1 = 1$ | $11$ |
| $22+5$ | $2+5 = 7$ | $27$ |
| $34+3$ | $4+3 = 7$ | $37$ |
| $71+6$ | $1+6 = 7$ | $77$ |

**Crossing a ten.** Go up to the round number first, then the rest.

$$28 + 7 \;=\; \underbrace{28 + 2}_{30} + 5 \;=\; 35$$
$$47 + 8 \;=\; \underbrace{47 + 3}_{50} + 5 \;=\; 55$$
$$66 + 9 \;=\; \underbrace{66 + 4}_{70} + 5 \;=\; 75$$

