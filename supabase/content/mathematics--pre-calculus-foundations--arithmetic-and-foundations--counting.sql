## 10. Multiplication — counting in steps

**Rule.** $a \times b$ is $b$ groups of $a$ — that is, $a$ added $b$ times.

$$5 \times 3 = 3 + 3 + 3 + 3 + 3 = 15$$

**Examples.**

| skip counting | as multiplication |
|---|---|
| $2, 4, 6, 8, 10$ | $2\times1 \ldots 2\times5$ |
| $3, 6, 9, 12, 15$ | $3\times1 \ldots 3\times5$ |
| $5, 10, 15, 20, 25$ | $5\times1 \ldots 5\times5$ |
| $10, 20, 30, 40, 50$ | $10\times1 \ldots 10\times5$ |

**Three facts.**

$$a\times b = b\times a \qquad a\times 1 = a \qquad a\times 0 = 0$$

$5\times3 = 3\times5$: five rows of three, turned a quarter turn, is three rows of five.

