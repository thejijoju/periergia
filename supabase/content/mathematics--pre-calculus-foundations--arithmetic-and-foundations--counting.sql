## 1. Counting a collection

**Rule.** Point at each object exactly once, saying the counting words in order. The last word is the answer.

**The one fact.** The answer does not depend on the order. So you may group.

**Examples.** The same row of $12$ marks, counted four ways:

| method | what you say | answer |
|---|---|---|
| left to right | 1, 2, 3, …, 12 | $12$ |
| right to left | 1, 2, 3, …, 12 | $12$ |
| in fives | 5, 10, then 2 more | $12$ |
| in twos | 2, 4, 6, 8, 10, 12 | $12$ |

$40 = 8$ groups of $5$. $30 = 3$ groups of $10$. Faster, and exact.

