## 2. The next number

**Rule.** Every number $n$ has exactly one **successor**, $n + 1$. There is no largest number.

**Rollovers.** A digit that is already $9$ returns to $0$ and passes one to its left.

**Examples.**

| $n$ | $n+1$ | | $n$ | $n-1$ |
|---|---|---|---|---|
| $7$ | $8$ | | $8$ | $7$ |
| $9$ | $10$ | | $10$ | $9$ |
| $39$ | $40$ | | $40$ | $39$ |
| $99$ | $100$ | | $100$ | $99$ |
| $999$ | $1000$ | | $200$ | $199$ |
| $1099$ | $1100$ | | $1000$ | $999$ |

